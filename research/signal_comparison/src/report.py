"""Build reports/RESULTS.md (all tables) from walkforward.json and final.json. Reads results only."""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import protocol as P
import study

NAMES = {"A1_DONCHIAN_TREND": "A1 Donchian + 4H EMA", "A2_COMBINED": "A2 Combined", "A3_VOTING": "A3 Voting"}


def f(x, nd=2, plus=False):
    if x is None:
        return "n/a"
    return f"{x:+.{nd}f}" if plus else f"{x:.{nd}f}"


def pval(p):
    if p is None:
        return "n/a"
    return "<0.001" if p < 0.001 else f"{p:.3f}"


def main_row(name, cand, m, extra):
    if not m.get("trades"):
        return f"| {name} | {cand} | 0 | | | | | | | | | | |"
    return (f"| {name} | {cand} | {m['trades']} | {f(m['win_rate_pct'], 1)}% | {f(m['profit_factor'])} | {f(m['expectancy_r'], 3, True)} | "
            f"{f(m['ci95_low'], 2, True)} to {f(m['ci95_high'], 2, True)} | {f(m['t_stat'])} | {pval(m['p_one_sided'])} | {pval(extra.get('holm'))} | "
            f"{pval(m['p_random'])} | {f(m['max_drawdown_r'], 1)}R / {f(m['max_drawdown_pct'], 1)}% | {extra.get('last', '')} |")


HEAD = ("| Approach | Setting | Trades | Win rate | Profit factor | Expectancy (R) | 95% CI | t | p | p (Holm) | p vs random entry | Max drawdown | {last} |\n"
        "|---|---|---|---|---|---|---|---|---|---|---|---|---|")


def main():
    with open(os.path.join(study.REPORTS_DIR, "walkforward.json")) as fh:
        wf = json.load(fh)
    with open(os.path.join(study.REPORTS_DIR, "final.json")) as fh:
        fin = json.load(fh)
    L = ["# Results tables", "",
         ("Generated by `src/report.py` from `walkforward.json` and `final.json`. All figures use the primary cost "
         "(measured Exness spread + 0.02% slippage) unless a column says otherwise. R is the initial risk of a trade (2 x ATR14)."),
         "`sel` rows use the parameter setting chosen by the walk-forward rule; `txt` rows use textbook settings with no selection.",
         ("p is one-sided for expectancy > 0. Holm adjusts for the 24 strategies of the same kind. "
         "'p vs random entry' is the share of 1,000 random-entry runs (same exit, direction and period) that did at least as well."), ""]
    for asset in P.ASSETS:
        wm, fm = wf[asset]["meta"], fin[asset]["meta"]
        L += [f"## {asset}", "",
              (f"- Walk-forward: {wm['walkforward'][0][:10]} to {wm['walkforward'][1][:10]}, {len(wm['folds'])} half-year folds. "
              f"Price change over the period {f(wm['walkforward_context']['buy_and_hold_pct'], 0, True)}%. "
              f"Regime mix (share of days): {wm['walkforward_context']['regime_share_pct']}."),
              (f"- Final test: {fm['final_test'][0][:10]} to {fm['final_test'][1][:10]}. "
              f"Price change {f(fm['final_context']['buy_and_hold_pct'], 0, True)}%. Regime mix: {fm['final_context']['regime_share_pct']}."),
              f"- Typical spread in the year before the final test: {f(wm['today_spread_pct'], 3)}% of price.", ""]
        for dname in P.DIRECTIONS:
            for exit_rule in P.EXITS:
                L += [f"### {asset} {dname} signals, {exit_rule} exit", "", "Walk-forward (out-of-sample, development zone)", "",
                      HEAD.format(last="Positive folds")]
                for ap in P.APPROACHES:
                    k = study.strategy_key(ap, dname, exit_rule)
                    s, fr = wf[asset]["strategies"][k], fin[asset]["strategies"][k]
                    for lab, wl, tag in (("selected", "walkforward_selected", "sel"), ("textbook", "walkforward_textbook", "txt")):
                        m = s[wl]
                        cands = sorted({x["candidate"] for x in m["folds"] if x.get("candidate")}) if lab == "selected" else ["s1"]
                        pos = m.get("positive_fold_share")
                        L.append(main_row(NAMES[ap], f"{tag}: {'/'.join(cands)}", m,
                                          {"holm": fr[lab].get("p_holm_walkforward"), "last": "n/a" if pos is None else f"{pos * 100:.0f}%"}))
                L += ["", "Final test (evaluated once)", "", HEAD.format(last="Verdict")]
                for ap in P.APPROACHES:
                    k = study.strategy_key(ap, dname, exit_rule)
                    fr = fin[asset]["strategies"][k]
                    for lab, tag in (("selected", "sel"), ("textbook", "txt")):
                        m = fr[lab]
                        L.append(main_row(NAMES[ap], f"{tag}: {m['candidate']}", m,
                                          {"holm": m.get("p_holm_final"), "last": "RELIABLE" if m["reliable"] else "not reliable"}))
                L += ["", "Cost sensitivity and regimes: expectancy in R (trades)", "",
                      "| Approach | Setting | Period | Spread only | Primary | Stress | Today's spread | Avg cost per trade | Avg hold | Bull | Bear | Sideways |",
                      "|---|---|---|---|---|---|---|---|---|---|---|---|"]
                for ap in P.APPROACHES:
                    k = study.strategy_key(ap, dname, exit_rule)
                    for lab, wl, tag in (("selected", "walkforward_selected", "sel"), ("textbook", "walkforward_textbook", "txt")):
                        for period, m in (("walk-forward", wf[asset]["strategies"][k][wl]), ("final", fin[asset]["strategies"][k][lab])):
                            if not m.get("trades"):
                                continue
                            reg = " | ".join(f"{f(m['regimes'][r]['expectancy_r'], 2, True)} ({m['regimes'][r]['trades']})" if m["regimes"][r]["trades"] else "none"
                                             for r in study.REGIMES)
                            L.append(f"| {NAMES[ap]} | {tag} | {period} | {f(m['expectancy_spread'], 3, True)} | {f(m['expectancy_r'], 3, True)} | "
                                     f"{f(m['expectancy_stress'], 3, True)} | {f(m['expectancy_today'], 3, True)} | {f(m['avg_cost_r_primary'], 3)}R | "
                                     f"{f(m['avg_hold_hours'], 0)}h | {reg} |")
                L.append("")
        L += [f"### {asset}: failed criteria per strategy (pre-registered pass rule)", "", "| Strategy | Setting | Verdict | Failed criteria |", "|---|---|---|---|"]
        for k, fr in fin[asset]["strategies"].items():
            ap, dname, exit_rule = k.split("|")
            for lab, tag in (("selected", "sel"), ("textbook", "txt")):
                m = fr[lab]
                L.append(f"| {NAMES[ap]} {dname} {exit_rule} | {tag}: {m['candidate']} | {'RELIABLE' if m['reliable'] else 'not reliable'} | {'; '.join(m['failed_criteria']) or 'none'} |")
        L.append("")
    with open(os.path.join(study.REPORTS_DIR, "RESULTS.md"), "w") as fh:
        fh.write("\n".join(L) + "\n")
    print("written", len(L), "lines")


if __name__ == "__main__":
    main()
